-- Laptop Repair Shop Database Schema (Fixed)

-- Enable Row Level Security
ALTER DATABASE postgres SET row_security = on;

-- Create enum types
DO $$ BEGIN
    CREATE TYPE repair_status AS ENUM (
      'received',
      'diagnosed',
      'waiting_parts',
      'in_progress',
      'completed',
      'ready_for_pickup',
      'delivered',
      'cancelled'
    );
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

DO $$ BEGIN
    CREATE TYPE repair_priority AS ENUM (
      'low',
      'normal',
      'high',
      'urgent'
    );
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

DO $$ BEGIN
    CREATE TYPE user_role AS ENUM (
      'shop_owner',
      'manager',
      'technician',
      'staff'
    );
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

-- Create sequence for ticket numbers FIRST
DROP SEQUENCE IF EXISTS repair_ticket_seq CASCADE;
CREATE SEQUENCE repair_ticket_seq START 1;

-- User profiles table (extends Supabase auth.users)
CREATE TABLE IF NOT EXISTS user_profiles (
  id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),

  full_name TEXT NOT NULL,
  role user_role NOT NULL DEFAULT 'staff',
  phone TEXT,
  is_active BOOLEAN DEFAULT true,

  -- Permissions
  can_create_users BOOLEAN DEFAULT false,
  can_manage_inventory BOOLEAN DEFAULT false,
  can_view_financials BOOLEAN DEFAULT false,
  can_delete_repairs BOOLEAN DEFAULT false,

  -- Metadata
  created_by UUID REFERENCES auth.users(id),
  notes TEXT
);

-- Customers table
CREATE TABLE IF NOT EXISTS customers (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),

  name TEXT NOT NULL,
  email TEXT UNIQUE,
  phone TEXT,
  address TEXT,

  notes TEXT,
  created_by UUID REFERENCES auth.users(id)
);

-- Repairs table (simplified ticket number generation)
CREATE TABLE IF NOT EXISTS repairs (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),

  customer_id UUID REFERENCES customers(id) ON DELETE CASCADE,

  -- Device information
  device_type TEXT NOT NULL DEFAULT 'Laptop',
  device_model TEXT NOT NULL,
  device_serial TEXT,

  -- Repair details
  issue_description TEXT NOT NULL,
  diagnosis TEXT,
  repair_notes TEXT,

  -- Status and priority
  status repair_status DEFAULT 'received',
  priority repair_priority DEFAULT 'normal',

  -- Cost information
  estimated_cost DECIMAL(10,2),
  final_cost DECIMAL(10,2),

  -- Dates
  estimated_completion DATE,
  completed_at TIMESTAMP WITH TIME ZONE,

  -- Staff tracking
  technician_id UUID REFERENCES auth.users(id),
  created_by UUID REFERENCES auth.users(id),
  updated_by UUID REFERENCES auth.users(id),

  -- Images
  images TEXT[] DEFAULT '{}',

  -- Ticket number (will be generated by trigger)
  ticket_number TEXT UNIQUE
);

-- Repair status logs table (for tracking status changes)
CREATE TABLE IF NOT EXISTS repair_status_logs (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),

  repair_id UUID REFERENCES repairs(id) ON DELETE CASCADE,
  old_status repair_status,
  new_status repair_status NOT NULL,
  notes TEXT,
  changed_by UUID REFERENCES auth.users(id)
);

-- Parts table
CREATE TABLE IF NOT EXISTS parts (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),

  name TEXT NOT NULL,
  description TEXT,
  sku TEXT UNIQUE,
  cost_price DECIMAL(10,2) NOT NULL,
  selling_price DECIMAL(10,2) NOT NULL,
  stock_quantity INTEGER DEFAULT 0,
  min_stock_level INTEGER DEFAULT 0,
  supplier TEXT,
  category TEXT,

  -- User tracking
  created_by UUID REFERENCES auth.users(id),
  updated_by UUID REFERENCES auth.users(id)
);

-- Repair parts junction table
CREATE TABLE IF NOT EXISTS repair_parts (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  repair_id UUID REFERENCES repairs(id) ON DELETE CASCADE,
  part_id UUID REFERENCES parts(id) ON DELETE CASCADE,
  quantity INTEGER NOT NULL DEFAULT 1,
  unit_price DECIMAL(10,2) NOT NULL
);

-- Customer feedback table
CREATE TABLE IF NOT EXISTS customer_feedback (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  repair_id UUID REFERENCES repairs(id) ON DELETE CASCADE,
  rating INTEGER NOT NULL CHECK (rating >= 1 AND rating <= 5),
  comments TEXT NOT NULL,
  submitted_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Create indexes for better performance
CREATE INDEX IF NOT EXISTS idx_user_profiles_role ON user_profiles(role);
CREATE INDEX IF NOT EXISTS idx_user_profiles_is_active ON user_profiles(is_active);
CREATE INDEX IF NOT EXISTS idx_repairs_customer_id ON repairs(customer_id);
CREATE INDEX IF NOT EXISTS idx_repairs_status ON repairs(status);
CREATE INDEX IF NOT EXISTS idx_repairs_created_at ON repairs(created_at);
CREATE INDEX IF NOT EXISTS idx_repairs_technician ON repairs(technician_id);
CREATE INDEX IF NOT EXISTS idx_repair_status_logs_repair_id ON repair_status_logs(repair_id);
CREATE INDEX IF NOT EXISTS idx_customers_email ON customers(email);
CREATE INDEX IF NOT EXISTS idx_customers_phone ON customers(phone);
CREATE INDEX IF NOT EXISTS idx_repairs_ticket_number ON repairs(ticket_number);

-- Create updated_at trigger function
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ language 'plpgsql';

-- Create triggers for updated_at
DROP TRIGGER IF EXISTS update_user_profiles_updated_at ON user_profiles;
CREATE TRIGGER update_user_profiles_updated_at BEFORE UPDATE ON user_profiles
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

DROP TRIGGER IF EXISTS update_customers_updated_at ON customers;
CREATE TRIGGER update_customers_updated_at BEFORE UPDATE ON customers
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

DROP TRIGGER IF EXISTS update_repairs_updated_at ON repairs;
CREATE TRIGGER update_repairs_updated_at BEFORE UPDATE ON repairs
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

DROP TRIGGER IF EXISTS update_parts_updated_at ON parts;
CREATE TRIGGER update_parts_updated_at BEFORE UPDATE ON parts
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

-- Create function to generate ticket numbers
CREATE OR REPLACE FUNCTION generate_ticket_number()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW.ticket_number IS NULL THEN
    NEW.ticket_number := 'TNL-' || to_char(NOW(), 'YYMMDD') || '-' || lpad(nextval('repair_ticket_seq')::text, 3, '0');
  END IF;
  RETURN NEW;
END;
$$ language 'plpgsql';

-- Create trigger for ticket number generation
DROP TRIGGER IF EXISTS generate_ticket_number_trigger ON repairs;
CREATE TRIGGER generate_ticket_number_trigger
  BEFORE INSERT ON repairs
  FOR EACH ROW EXECUTE FUNCTION generate_ticket_number();

-- Create function to log status changes
CREATE OR REPLACE FUNCTION log_repair_status_change()
RETURNS TRIGGER AS $$
BEGIN
  IF OLD.status IS DISTINCT FROM NEW.status THEN
    INSERT INTO repair_status_logs (repair_id, old_status, new_status, changed_by)
    VALUES (NEW.id, OLD.status, NEW.status, auth.uid());
  END IF;
  RETURN NEW;
END;
$$ language 'plpgsql';

-- Create trigger for status logging
DROP TRIGGER IF EXISTS log_repair_status_changes ON repairs;
CREATE TRIGGER log_repair_status_changes AFTER UPDATE ON repairs
  FOR EACH ROW EXECUTE FUNCTION log_repair_status_change();

-- Function to create user profile automatically
CREATE OR REPLACE FUNCTION create_user_profile()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO user_profiles (id, full_name, role)
  VALUES (
    NEW.id,
    COALESCE(NEW.raw_user_meta_data->>'full_name', NEW.email),
    COALESCE((NEW.raw_user_meta_data->>'role')::user_role, 'staff')
  )
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$$ language 'plpgsql';

-- Trigger to create profile when user signs up
DROP TRIGGER IF EXISTS create_profile_on_signup ON auth.users;
CREATE TRIGGER create_profile_on_signup
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION create_user_profile();

